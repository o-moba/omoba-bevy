//! Build step: `client/assets/ui/verdant/manifest.json` (written by
//! `scripts/sync_ui_assets.py` from the omoba-ui handoff manifest) becomes
//! `OUT_DIR/ui_assets.rs`: one enum per asset kind (`Icon`, `Frame`,
//! `Sprite`, `Background`) with each variant's 1x/2x paths, 9-slice insets
//! and atlas grid. Kit code names `Icon::NavLock`; an icon the data lacks is a
//! compile error, and the paths cannot drift from the installed files.
use std::{fmt::Write as _, path::Path};

use serde_json::Value;

/// Asset paths Bevy loads are relative to `client/assets`.
const PREFIX: &str = "ui/verdant/";

fn camel(words: &str) -> String {
    words
        .split(['-', '_', '/', '.'])
        .map(|word| {
            let mut chars = word.chars();
            chars.next().map_or_else(String::new, |first| {
                first.to_ascii_uppercase().to_string() + chars.as_str()
            })
        })
        .collect()
}

fn float(value: f64) -> String {
    let text = format!("{value:?}");
    if text.contains('.') {
        text
    } else {
        format!("{text}.0")
    }
}

fn number(value: &Value, what: &str) -> f64 {
    value
        .as_f64()
        .unwrap_or_else(|| panic!("asset manifest: {what} must be a number"))
}

struct Entry {
    variant: String,
    path: String,
    path_2x: Option<String>,
    raw: Value,
}

fn stem(path: &str) -> &str {
    path.rsplit_once('.')
        .map_or(path, |(stem, _)| stem)
        .trim_end_matches("@1x")
}

pub(crate) fn render(manifest: &Value, assets: &Path) -> String {
    let entries = manifest["assets"]
        .as_array()
        .expect("asset manifest: assets array");
    let mut icons = Vec::new();
    let mut frames = Vec::new();
    let mut sprites = Vec::new();
    let mut backgrounds: Vec<(String, Option<String>, Option<String>)> = Vec::new();
    for raw in entries {
        let path = raw["path"]
            .as_str()
            .expect("asset manifest: path")
            .to_owned();
        let path_2x = raw["path_2x"].as_str().map(str::to_owned);
        for file in std::iter::once(&path).chain(path_2x.as_ref()) {
            assert!(
                assets.join(PREFIX).join(file).is_file(),
                "asset manifest lists {file}, which is not installed (run scripts/sync_ui_assets.py)"
            );
        }
        let (kind, rest) = path.split_once('/').expect("asset manifest: kind/");
        match kind {
            "icons" => icons.push(Entry {
                variant: camel(stem(rest)),
                path,
                path_2x,
                raw: raw.clone(),
            }),
            "frames" => frames.push(Entry {
                variant: camel(stem(rest)),
                path,
                path_2x,
                raw: raw.clone(),
            }),
            "sprites" => sprites.push(Entry {
                variant: camel(stem(rest)),
                path,
                path_2x,
                raw: raw.clone(),
            }),
            "backgrounds" => {
                let file_stem = stem(rest);
                let (name, resolution) = file_stem
                    .rsplit_once('-')
                    .expect("backgrounds are <name>-<height>.jpg");
                let variant = camel(name);
                let slot = match backgrounds.iter().position(|(v, _, _)| *v == variant) {
                    Some(index) => index,
                    None => {
                        backgrounds.push((variant, None, None));
                        backgrounds.len() - 1
                    }
                };
                match resolution {
                    "1080" => backgrounds[slot].2 = Some(path.clone()),
                    "720" => backgrounds[slot].1 = Some(path.clone()),
                    other => panic!("background {path}: unknown resolution {other}"),
                }
            }
            // `icons/LICENSES.md` is shipped text, not a texture.
            _ if path.ends_with(".md") || path.ends_with(".txt") => {}
            "fonts" => {}
            other => panic!("asset manifest: unknown kind {other:?} ({path})"),
        }
    }
    icons.retain(|entry| entry.path.ends_with(".png"));
    let mut out = String::from(
        "// @generated by client/build.rs from client/assets/ui/verdant/manifest.json. Do not edit.\n",
    );
    render_enum(
        &mut out,
        "Icon",
        "A white-on-alpha glyph (`icons/<group>/<name>`), tinted with `ImageNode::color`.",
        &icons,
    );
    let _ = writeln!(out, "impl Icon {{");
    render_paths(&mut out, "Icon", &icons);
    let _ = writeln!(out, "}}\n");
    render_enum(
        &mut out,
        "Frame",
        "A 9-slice frame or button slab (`frames/*`), not tintable.",
        &frames,
    );
    let _ = writeln!(out, "impl Frame {{");
    render_paths(&mut out, "Frame", &frames);
    render_insets(&mut out, "Frame", &frames);
    render_size(&mut out, "Frame", &frames);
    let _ = writeln!(out, "}}\n");
    render_enum(
        &mut out,
        "Sprite",
        "A tintable sprite or atlas (`sprites/*`).",
        &sprites,
    );
    let _ = writeln!(out, "impl Sprite {{");
    render_paths(&mut out, "Sprite", &sprites);
    render_insets(&mut out, "Sprite", &sprites);
    render_size(&mut out, "Sprite", &sprites);
    let _ = writeln!(
        out,
        "    /// Atlas grid at a density, if the sprite is an atlas.\n    pub const fn atlas(self, hi: bool) -> Option<AtlasGrid> {{\n        match (self, hi) {{"
    );
    for entry in &sprites {
        if let Some(atlas) = entry.raw.get("atlas").filter(|atlas| !atlas.is_null()) {
            for (hi, key) in [(false, "at_1x"), (true, "at_2x")] {
                let grid = &atlas[key];
                let _ = writeln!(
                    out,
                    "            (Sprite::{}, {hi}) => Some(AtlasGrid {{ frame: {}, columns: {}, rows: {}, frames: {}, padding: {} }}),",
                    entry.variant,
                    number(&grid["frame_w"], "frame_w") as u32,
                    number(&grid["columns"], "columns") as u32,
                    number(&grid["rows"], "rows") as u32,
                    number(&grid["frames"], "frames") as u32,
                    number(&grid["padding"][0], "padding") as u32,
                );
            }
        }
    }
    let _ = writeln!(out, "            _ => None,\n        }}\n    }}\n}}\n");
    let _ = writeln!(
        out,
        "/// A full-screen menu background (`backgrounds/<name>-720|1080.jpg`).\n#[derive(Clone, Copy, PartialEq, Eq, Hash, Debug)]\npub enum Background {{"
    );
    for (variant, _, _) in &backgrounds {
        let _ = writeln!(out, "    {variant},");
    }
    let _ = writeln!(
        out,
        "}}\n\nimpl Background {{\n    pub const ALL: [Background; {}] = [{}];\n\n    /// The 1920×1080 image when `hi`, else 1280×720.\n    pub const fn path(self, hi: bool) -> &'static str {{\n        match (self, hi) {{",
        backgrounds.len(),
        backgrounds
            .iter()
            .map(|(variant, _, _)| format!("Background::{variant}"))
            .collect::<Vec<_>>()
            .join(", ")
    );
    for (variant, low, high) in &backgrounds {
        let low = low
            .as_ref()
            .unwrap_or_else(|| panic!("{variant}: no 720 image"));
        let high = high
            .as_ref()
            .unwrap_or_else(|| panic!("{variant}: no 1080 image"));
        let _ = writeln!(
            out,
            "            (Background::{variant}, false) => \"{PREFIX}{low}\",\n            (Background::{variant}, true) => \"{PREFIX}{high}\","
        );
    }
    let _ = writeln!(out, "        }}\n    }}\n}}");
    out
}

fn render_enum(out: &mut String, name: &str, doc: &str, entries: &[Entry]) {
    let _ = writeln!(
        out,
        "/// {doc}\n#[derive(Clone, Copy, PartialEq, Eq, Hash, Debug)]\npub enum {name} {{"
    );
    for entry in entries {
        let _ = writeln!(out, "    /// `{}`\n    {},", entry.path, entry.variant);
    }
    let _ = writeln!(out, "}}\n");
}

fn render_paths(out: &mut String, name: &str, entries: &[Entry]) {
    let _ = writeln!(
        out,
        "    pub const ALL: [{name}; {}] = [{}];\n\n    /// Asset path at a density: `@2x` when `hi`.\n    pub const fn path(self, hi: bool) -> &'static str {{\n        match (self, hi) {{",
        entries.len(),
        entries
            .iter()
            .map(|entry| format!("{name}::{}", entry.variant))
            .collect::<Vec<_>>()
            .join(", ")
    );
    for entry in entries {
        let high = entry.path_2x.as_ref().unwrap_or(&entry.path);
        let _ = writeln!(
            out,
            "            ({name}::{v}, false) => \"{PREFIX}{}\",\n            ({name}::{v}, true) => \"{PREFIX}{high}\",",
            entry.path,
            v = entry.variant
        );
    }
    let _ = writeln!(out, "        }}\n    }}\n");
}

/// 9-slice insets in 1x logical px `[left, top, right, bottom]` (the 2x
/// texture holds twice as many pixels).
fn render_insets(out: &mut String, name: &str, entries: &[Entry]) {
    let _ = writeln!(
        out,
        "    /// 9-slice insets in 1x px `[left, top, right, bottom]`, if sliced.\n    pub const fn insets(self) -> Option<[f32; 4]> {{\n        match self {{"
    );
    for entry in entries {
        if let Some(slice) = entry.raw.get("nine_slice").filter(|slice| !slice.is_null()) {
            let _ = writeln!(
                out,
                "            {name}::{} => Some([{}, {}, {}, {}]),",
                entry.variant,
                float(number(&slice["left"], "left")),
                float(number(&slice["top"], "top")),
                float(number(&slice["right"], "right")),
                float(number(&slice["bottom"], "bottom"))
            );
        }
    }
    let _ = writeln!(
        out,
        "            #[allow(unreachable_patterns)]\n            _ => None,\n        }}\n    }}\n"
    );
}

fn render_size(out: &mut String, name: &str, entries: &[Entry]) {
    let _ = writeln!(
        out,
        "    /// Texture size at 1x (logical px).\n    pub const fn size(self) -> (f32, f32) {{\n        match self {{"
    );
    for entry in entries {
        let size = &entry.raw["size_1x"];
        let _ = writeln!(
            out,
            "            {name}::{} => ({}, {}),",
            entry.variant,
            float(number(&size[0], "size_1x")),
            float(number(&size[1], "size_1x"))
        );
    }
    let _ = writeln!(out, "        }}\n    }}");
}
