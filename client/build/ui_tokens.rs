//! Build step: `client/ui/tokens/verdant-crown.json` (the Verdant Crown design
//! tokens mirrored from the omoba-ui handoff by `scripts/sync_ui_tokens.py`)
//! becomes `OUT_DIR/ui_tokens.rs`, typed constants included by
//! `client/src/ui/tokens.rs`. A token the code names but the data lacks is a
//! compile error; a token the generator cannot type fails the build.
//!
//! Naming: the group becomes a module, the rest of the key an upper-case
//! constant (`color.surface.1.opaque` → `color::SURFACE_1_OPAQUE`,
//! `space.8` → `space::S8`). A `.desktop`/`.phone` pair becomes one profile
//! aware `Metric` (`size.button.height.*` → `size::BUTTON_HEIGHT`); a lone
//! `.phone` or `.desktop` value keeps its suffix. `font.family.*` becomes the
//! `FontFamily` enum, `type.<style>.*` a `TypeStyle` constant and a
//! `TextRole` variant. Every key also lands in one lookup table
//! (`COLOR_TOKENS`, `NUMBER_TOKENS`, `TEXT_TOKENS`), which the client tests
//! compare with the JSON, so the generated code and the data cannot drift.
use std::{collections::BTreeMap, fmt::Write as _, path::Path};

use serde_json::{Map, Value};

/// Folder of the install root of the handoff manifest, relative to
/// `client/assets` (where Bevy's asset server loads from).
const INSTALL_ROOT: &str = "ui/verdant/";

pub(crate) fn render(tokens: &Map<String, Value>, assets: &Path) -> String {
    let mut out = String::from(
        "// @generated by client/build.rs from client/ui/tokens/verdant-crown.json. Do not edit.\n",
    );
    let mut colors = Vec::new();
    let mut numbers: Vec<(String, f64)> = Vec::new();
    let mut texts: Vec<(String, String)> = Vec::new();
    let mut groups: BTreeMap<&str, Vec<(&str, &Value)>> = BTreeMap::new();
    for (key, value) in tokens {
        if key.starts_with('$') {
            continue;
        }
        let (group, rest) = key
            .split_once('.')
            .unwrap_or_else(|| panic!("token {key:?} has no group"));
        groups.entry(group).or_default().push((rest, value));
    }
    for (group, entries) in &groups {
        match *group {
            "color" => render_colors(&mut out, entries, &mut colors),
            "space" | "radius" | "border" | "size" => {
                render_numbers(&mut out, group, entries, &mut numbers, &mut texts)
            }
            "motion" => render_motion(&mut out, entries, &mut numbers, &mut texts),
            "font" => render_fonts(&mut out, entries, assets, &mut texts),
            "type" => render_types(&mut out, tokens, entries, &mut numbers, &mut texts),
            other => panic!("unknown token group {other:?}"),
        }
    }
    out.push_str("/// Every colour token, for the data round-trip test.\npub const COLOR_TOKENS: &[(&str, Color)] = &[\n");
    for (key, ident) in &colors {
        let _ = writeln!(out, "    ({key:?}, color::{ident}),");
    }
    out.push_str("];\n/// Every numeric token (motion durations in ms), for the data round-trip test.\npub const NUMBER_TOKENS: &[(&str, f32)] = &[\n");
    for (key, value) in &numbers {
        let _ = writeln!(out, "    ({key:?}, {}),", float(*value));
    }
    out.push_str("];\n/// Every string token (font paths, type families and cases, easings, notes).\npub const TEXT_TOKENS: &[(&str, &str)] = &[\n");
    for (key, value) in &texts {
        let _ = writeln!(out, "    ({key:?}, {value:?}),");
    }
    out.push_str("];\n");
    out
}

fn ident(path: &str) -> String {
    let ident = path.replace(['.', '-'], "_").to_uppercase();
    assert!(
        ident
            .chars()
            .all(|character| character.is_ascii_alphanumeric() || character == '_'),
        "token name {path:?} is not a Rust identifier"
    );
    if ident.starts_with(|character: char| character.is_ascii_digit()) {
        format!("S{ident}")
    } else {
        ident
    }
}

fn camel(path: &str) -> String {
    path.split(['.', '_'])
        .map(|word| {
            let mut chars = word.chars();
            chars.next().map_or_else(String::new, |first| {
                first.to_ascii_uppercase().to_string() + chars.as_str()
            })
        })
        .collect()
}

fn float(value: f64) -> String {
    // f32 shortest form: the constants are f32, so more digits are noise.
    let text = format!("{:?}", value as f32);
    if text.contains('.') || text.contains('e') {
        text
    } else {
        format!("{text}.0")
    }
}

fn number(key: &str, value: &Value) -> f64 {
    value
        .as_f64()
        .unwrap_or_else(|| panic!("token {key:?} must be a number, got {value}"))
}

fn render_colors(out: &mut String, entries: &[(&str, &Value)], table: &mut Vec<(String, String)>) {
    out.push_str("/// `color.*`: sRGB colours (`#RRGGBBAA` in the data).\npub mod color {\n    use bevy::color::Color;\n");
    for (rest, value) in entries {
        let key = format!("color.{rest}");
        let hex = value
            .as_str()
            .filter(|hex| hex.len() == 9 && hex.starts_with('#'))
            .unwrap_or_else(|| panic!("{key} must be #RRGGBBAA, got {value}"));
        let channel = |index: usize| {
            u8::from_str_radix(&hex[1 + index * 2..3 + index * 2], 16)
                .unwrap_or_else(|_| panic!("{key}: bad hex {hex}"))
        };
        let [r, g, b, a] = [channel(0), channel(1), channel(2), channel(3)];
        let name = ident(rest);
        let _ = writeln!(
            out,
            "    /// `{key}` {hex}\n    pub const {name}: Color = Color::srgba({}, {}, {}, {});",
            float(f64::from(r) / 255.0),
            float(f64::from(g) / 255.0),
            float(f64::from(b) / 255.0),
            float(f64::from(a) / 255.0)
        );
        table.push((key, name));
    }
    out.push_str("}\n");
}

/// Splits `button.height.desktop` into (`button.height`, Some("desktop")).
fn profile_suffix(rest: &str) -> (&str, Option<&str>) {
    for profile in ["desktop", "phone"] {
        if let Some(stem) = rest.strip_suffix(&format!(".{profile}")) {
            return (stem, Some(profile));
        }
    }
    (rest, None)
}

fn render_numbers(
    out: &mut String,
    group: &str,
    entries: &[(&str, &Value)],
    numbers: &mut Vec<(String, f64)>,
    texts: &mut Vec<(String, String)>,
) {
    let _ = writeln!(
        out,
        "/// `{group}.*`: logical px at the reference resolution.\npub mod {group} {{\n    #[allow(unused_imports)]\n    use super::Metric;"
    );
    let lookup: BTreeMap<&str, &Value> = entries.iter().copied().collect();
    for (rest, value) in entries {
        let key = format!("{group}.{rest}");
        if let Some(note) = value.as_str() {
            let _ = writeln!(
                out,
                "    /// `{key}` (a note for the engineer, not a size)\n    pub const {}: &str = {note:?};",
                ident(rest)
            );
            texts.push((key, note.to_owned()));
            continue;
        }
        let value = number(&key, value);
        numbers.push((key.clone(), value));
        match profile_suffix(rest) {
            (stem, Some("desktop")) if lookup.contains_key(format!("{stem}.phone").as_str()) => {
                let phone = number(&key, lookup[format!("{stem}.phone").as_str()]);
                let _ = writeln!(
                    out,
                    "    /// `{group}.{stem}.desktop` / `.phone`\n    pub const {}: Metric = Metric::new({}, {});",
                    ident(stem),
                    float(value),
                    float(phone)
                );
            }
            (stem, Some("phone")) if lookup.contains_key(format!("{stem}.desktop").as_str()) => {}
            _ => {
                let _ = writeln!(
                    out,
                    "    /// `{key}`\n    pub const {}: f32 = {};",
                    ident(rest),
                    float(value)
                );
            }
        }
    }
    out.push_str("}\n");
}

fn render_motion(
    out: &mut String,
    entries: &[(&str, &Value)],
    numbers: &mut Vec<(String, f64)>,
    texts: &mut Vec<(String, String)>,
) {
    out.push_str("/// `motion.*`: durations, easings and scales.\npub mod motion {\n    use super::CubicBezier;\n    use std::time::Duration;\n");
    for (rest, value) in entries {
        let key = format!("motion.{rest}");
        if let Some(duration) = rest.strip_prefix("duration.") {
            let millis = number(&key, value);
            assert!(
                millis >= 0.0 && millis.fract() == 0.0,
                "{key} must be whole milliseconds"
            );
            let _ = writeln!(
                out,
                "    /// `{key}` ({millis} ms)\n    pub const {}: Duration = Duration::from_millis({});",
                ident(&format!("duration.{duration}")),
                millis as u64
            );
            numbers.push((key, millis));
        } else if rest.starts_with("easing.") {
            let text = value
                .as_str()
                .unwrap_or_else(|| panic!("{key} must be a string"));
            let inner = text
                .strip_prefix("cubic-bezier(")
                .and_then(|inner| inner.strip_suffix(')'))
                .unwrap_or_else(|| panic!("{key} must be cubic-bezier(a, b, c, d), got {text}"));
            let points: Vec<f64> = inner
                .split(',')
                .map(|point| {
                    point
                        .trim()
                        .parse()
                        .unwrap_or_else(|_| panic!("{key}: bad number in {text}"))
                })
                .collect();
            assert_eq!(points.len(), 4, "{key}: cubic-bezier takes four numbers");
            let _ = writeln!(
                out,
                "    /// `{key}` {text}\n    pub const {}: CubicBezier = CubicBezier::new({}, {}, {}, {});",
                ident(rest),
                float(points[0]),
                float(points[1]),
                float(points[2]),
                float(points[3])
            );
            texts.push((key, text.to_owned()));
        } else {
            let value = number(&key, value);
            let _ = writeln!(
                out,
                "    /// `{key}`\n    pub const {}: f32 = {};",
                ident(rest),
                float(value)
            );
            numbers.push((key, value));
        }
    }
    out.push_str("}\n");
}

/// `assets/fonts/X` (handoff path) → `ui/verdant/fonts/X`; `client/assets/X`
/// (a font the game already ships) → `X`.
fn font_asset_path(key: &str, path: &str) -> String {
    if let Some(rest) = path.strip_prefix("assets/") {
        format!("{INSTALL_ROOT}{rest}")
    } else if let Some(rest) = path.strip_prefix("client/assets/") {
        rest.to_owned()
    } else {
        panic!("{key}: font path {path:?} is outside assets/ and client/assets/")
    }
}

fn render_fonts(
    out: &mut String,
    entries: &[(&str, &Value)],
    assets: &Path,
    texts: &mut Vec<(String, String)>,
) {
    let mut variants = Vec::new();
    for (rest, value) in entries {
        let key = format!("font.{rest}");
        let family = rest
            .strip_prefix("family.")
            .unwrap_or_else(|| panic!("{key}: fonts are font.family.*"));
        let path = value
            .as_str()
            .unwrap_or_else(|| panic!("{key} must be a file path"));
        let asset = font_asset_path(&key, path);
        assert!(
            assets.join(&asset).is_file(),
            "{key}: {asset} is not installed under client/assets (run scripts/sync_ui_assets.py)"
        );
        variants.push((camel(family), key.clone(), asset));
        texts.push((key, path.to_owned()));
    }
    out.push_str("/// `font.family.*`: the UI font faces.\n#[derive(Clone, Copy, PartialEq, Eq, Hash, Debug)]\npub enum FontFamily {\n");
    for (variant, key, _) in &variants {
        let _ = writeln!(out, "    /// `{key}`\n    {variant},");
    }
    let _ = writeln!(
        out,
        "}}\n\nimpl FontFamily {{\n    pub const ALL: [FontFamily; {}] = [{}];\n\n    /// The token name.\n    pub const fn token(self) -> &'static str {{\n        match self {{",
        variants.len(),
        variants
            .iter()
            .map(|(variant, _, _)| format!("FontFamily::{variant}"))
            .collect::<Vec<_>>()
            .join(", ")
    );
    for (variant, key, _) in &variants {
        let _ = writeln!(out, "            FontFamily::{variant} => {key:?},");
    }
    out.push_str("        }\n    }\n\n    /// Asset path the `AssetServer` loads the face from.\n    pub const fn asset_path(self) -> &'static str {\n        match self {\n");
    for (variant, _, asset) in &variants {
        let _ = writeln!(out, "            FontFamily::{variant} => {asset:?},");
    }
    out.push_str("        }\n    }\n\n    /// `font.family.*` token name → face.\n    pub fn from_token(token: &str) -> Option<Self> {\n        Self::ALL.into_iter().find(|family| family.token() == token)\n    }\n}\n");
}

fn render_types(
    out: &mut String,
    tokens: &Map<String, Value>,
    entries: &[(&str, &Value)],
    numbers: &mut Vec<(String, f64)>,
    texts: &mut Vec<(String, String)>,
) {
    let mut styles: Vec<&str> = Vec::new();
    for (rest, value) in entries {
        let (style, field) = rest
            .split_once('.')
            .unwrap_or_else(|| panic!("type.{rest}: type keys are type.<style>.<field>"));
        if !styles.contains(&style) {
            styles.push(style);
        }
        let key = format!("type.{rest}");
        match field {
            "family" | "cjk.family" | "case" => {
                texts.push((key, value.as_str().expect("string").to_owned()))
            }
            "size.desktop"
            | "size.phone"
            | "line_height"
            | "letter_spacing_em"
            | "cjk.letter_spacing_em" => numbers.push((key.clone(), number(&key, value))),
            other => panic!("{key}: unknown type field {other:?}"),
        }
    }
    let get = |style: &str, field: &str| -> &Value {
        tokens
            .get(&format!("type.{style}.{field}"))
            .unwrap_or_else(|| panic!("type.{style} is missing {field}"))
    };
    let family = |style: &str, field: &str| -> String {
        let reference = get(style, field)
            .as_str()
            .unwrap_or_else(|| panic!("type.{style}.{field} must name a font.family token"));
        let rest = reference
            .strip_prefix("font.family.")
            .filter(|_| tokens.contains_key(reference))
            .unwrap_or_else(|| panic!("type.{style}.{field}: {reference:?} is not a font token"));
        format!("FontFamily::{}", camel(rest))
    };
    out.push_str("/// `type.<style>.*`: the named type styles.\npub mod type_style {\n    use super::{FontFamily, Metric, TextCase, TypeStyle};\n");
    for style in &styles {
        let key = format!("type.{style}.size.desktop");
        let case = match get(style, "case").as_str() {
            Some("upper") => "TextCase::Upper",
            Some("none") => "TextCase::AsWritten",
            other => panic!("type.{style}.case must be upper or none, got {other:?}"),
        };
        let _ = writeln!(
            out,
            "    /// `type.{style}.*`\n    pub const {}: TypeStyle = TypeStyle {{\n        family: {},\n        size: Metric::new({}, {}),\n        line_height: {},\n        letter_spacing_em: {},\n        case: {case},\n        cjk_family: {},\n        cjk_letter_spacing_em: {},\n    }};",
            ident(style),
            family(style, "family"),
            float(number(&key, get(style, "size.desktop"))),
            float(number(&key, get(style, "size.phone"))),
            float(number(&key, get(style, "line_height"))),
            float(number(&key, get(style, "letter_spacing_em"))),
            family(style, "cjk.family"),
            float(number(&key, get(style, "cjk.letter_spacing_em"))),
        );
    }
    out.push_str("}\n\n/// One variant per `type.<style>`; `style()` is its `TypeStyle`.\n#[derive(Clone, Copy, PartialEq, Eq, Hash, Debug)]\npub enum TextRole {\n");
    for style in &styles {
        let _ = writeln!(out, "    /// `type.{style}`\n    {},", camel(style));
    }
    let _ = writeln!(
        out,
        "}}\n\nimpl TextRole {{\n    pub const ALL: [TextRole; {}] = [{}];\n\n    pub const fn style(self) -> TypeStyle {{\n        match self {{",
        styles.len(),
        styles
            .iter()
            .map(|style| format!("TextRole::{}", camel(style)))
            .collect::<Vec<_>>()
            .join(", ")
    );
    for style in &styles {
        let _ = writeln!(
            out,
            "            TextRole::{} => type_style::{},",
            camel(style),
            ident(style)
        );
    }
    out.push_str("        }\n    }\n\n    /// The style's token name (`type.<style>`).\n    pub const fn token(self) -> &'static str {\n        match self {\n");
    for style in &styles {
        let _ = writeln!(
            out,
            "            TextRole::{} => \"type.{style}\",",
            camel(style)
        );
    }
    out.push_str("        }\n    }\n}\n");
}
