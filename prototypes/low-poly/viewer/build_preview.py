"""Bundle an OMOBA browser prototype and its Blender assets for offline use."""

import argparse
import base64
from pathlib import Path


VIEWER = Path(__file__).resolve().parent
PROTOTYPE = VIEWER.parent
COMMON_MODULES = [VIEWER / "glb.js", VIEWER / "render.js"]


def embed_model(script_id, filename):
    encoded = base64.b64encode((PROTOTYPE / filename).read_bytes()).decode("ascii")
    return f'<script type="application/octet-stream" id="{script_id}">{encoded}</script>'


def inline_module(path):
    source = path.read_text(encoding="utf-8")
    return "\n".join(line.removeprefix("export ") for line in source.splitlines()
                     if not line.startswith("import "))


def build_page(folder, output, modules, assets):
    html = (folder / "index.html").read_text(encoding="utf-8")
    css = (folder / "style.css").read_text(encoding="utf-8")
    html = html.replace("<!doctype html>", "<!doctype html>\n<!-- Generated by build_preview.py. -->")
    html = html.replace('<link rel="stylesheet" href="style.css">', f"<style>\n{css}</style>")
    html = html.replace(f'  <script type="module" src="{modules[-1].name}"></script>\n', "")
    inline = [
        *(embed_model(script_id, filename) for script_id, filename in assets),
        '<script type="module">',
        *(inline_module(path) for path in [*COMMON_MODULES, *modules]),
        "</script>",
        "</body>",
    ]
    html = html.replace("</body>", "\n".join(inline))
    (folder / output).write_text(html, encoding="utf-8")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--aram", action="store_true", help="Bundle the playable ARAM prototype")
    if parser.parse_args().aram:
        aram = PROTOTYPE / "aram"
        build_page(aram, "play.html", [aram / "match.mjs", aram / "game.mjs"], [
            ("aram-arena-model", "aram-arena.glb"), ("aram-character-model", "character-preview.glb"),
        ])
    else:
        build_page(VIEWER, "preview.html", [VIEWER / "viewer.js"], [
            ("arena-model", "arena.glb"), ("character-model", "character-preview.glb"),
        ])


if __name__ == "__main__":
    main()
